import {cp,mkdir,rm,stat} from 'node:fs/promises';
import {readFileSync} from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
const root=process.cwd(),pkg=JSON.parse(readFileSync(path.join(root,'package.json'),'utf8'));
if(!/^\d+\.\d+\.\d+(?:-[\w.]+)?$/.test(pkg.version))throw Error('Invalid version');
const folder=`danmakullottery-Windows-x64-v${pkg.version}`;
const staging=path.join(root,'.build-cache','portable');
const release=path.join(root,'release',`v${pkg.version}`),source=path.join(release,'win-unpacked');
await stat(path.join(source,'resources','app.asar'));
if(path.resolve(staging)!==path.resolve(root,'.build-cache','portable'))throw Error('Invalid staging path');
await rm(staging,{recursive:true,force:true});await mkdir(staging,{recursive:true});await cp(source,path.join(staging,folder),{recursive:true});
const archive=path.join(release,`${folder}.zip`);await rm(archive,{force:true});
const require=createRequire(import.meta.resolve('electron-builder'));
execFileSync(require('7zip-bin').path7za,['a','-tzip','-mx=7',archive,folder],{cwd:staging,windowsHide:true,stdio:'inherit'});
const listing=execFileSync(require('7zip-bin').path7za,['l','-slt',archive],{encoding:'utf8',windowsHide:true});
const entries=listing.split('----------')[1]?.split(/\r?\n/).filter(line=>line.startsWith('Path = ')).map(line=>line.slice(7))??[];
if(!entries.length||entries.some(name=>name!==folder&&!name.startsWith(folder+'/')&&!name.startsWith(folder+'\\')))throw Error('Portable ZIP must have exactly one top-level folder');
console.log(`Verified ${entries.length} ZIP entries inside ${folder}/`);
